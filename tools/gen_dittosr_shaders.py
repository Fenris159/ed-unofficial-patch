#!/usr/bin/env python3
"""Compile third_party/dittosr/shaders to Direct3D 11 bytecode.

Writes src/d3d11/dittosr_shader_bytecode.h. Needs DXC on PATH, or DXC pointing
at the dxc binary (a DirectX Shader Compiler that can target cs_5_0). The DLL
creates its compute shaders from this bytecode, so a player's machine does not
compile HLSL.
"""
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "third_party" / "dittosr" / "shaders"
OUT = ROOT / "src" / "d3d11" / "dittosr_shader_bytecode.h"
PASSES = (
    ("convert", ""),
    ("motion", ""),
    ("upscale", "#define ANTI_SHIMMER 1\n"),
    ("sharpen", "#define ANTI_SHIMMER 1\n"),
)


def dxc_path() -> str:
    env = os.environ.get("DXC")
    if env:
        return env
    found = shutil.which("dxc")
    if not found:
        raise SystemExit("gen_dittosr_shaders: set DXC to a dxc binary that targets cs_5_0")
    return found


def source(name: str, defines: str) -> str:
    common = (SRC / "common.hlsli").read_text()
    body = (SRC / f"{name}.hlsl").read_text().replace('#include "common.hlsli"\n', "")
    return common + "\n" + defines + body


def compile_pass(dxc: str, name: str, defines: str, directory: pathlib.Path) -> bytes:
    src = directory / f"{name}.hlsl"
    blob = directory / f"{name}.cso"
    src.write_text(source(name, defines))
    run = subprocess.run([dxc, "-T", "cs_5_0", "-E", "main", "-O3", "-Fo", str(blob), str(src)],
                         capture_output=True, text=True)
    if run.returncode != 0:
        sys.stderr.write(run.stdout + run.stderr)
        raise SystemExit(f"gen_dittosr_shaders: {name} did not compile")
    return blob.read_bytes()


def c_array(name: str, data: bytes) -> str:
    lines = [f"inline constexpr unsigned char kDitto{name.capitalize()}Dxbc[] = {{"]
    row = []
    for i, byte in enumerate(data):
        row.append(f"0x{byte:02x}")
        if len(row) == 16:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    dxc = dxc_path()
    parts = [
        "// Generated by tools/gen_dittosr_shaders.py from third_party/dittosr/shaders.",
        "// DittoSR 0.5.0, shader model 5. Do not edit; regenerate after a shader change.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
    ]
    with tempfile.TemporaryDirectory() as tmp:
        directory = pathlib.Path(tmp)
        for name, defines in PASSES:
            data = compile_pass(dxc, name, defines, directory)
            parts.append(c_array(name, data))
            parts.append("")
    OUT.write_text("\n".join(parts) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
